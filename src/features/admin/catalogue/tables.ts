export function tableByKey(key: string, zone?: "catalogue" | "cms"): TableDef | undefined {
  return TABLES.find((def) => def.key === key && (!zone || def.zone === zone));
}

export function kindOf(def: TableDef, field: string): FieldKind {
  if (field === "status" && def.status) return { kind: "enum", enum: def.status };
  return def.kinds[field] ?? FIELD_KINDS[field] ?? { kind: "text" };
}
