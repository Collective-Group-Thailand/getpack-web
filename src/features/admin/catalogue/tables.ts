export type Section = "structure" | "materials" | "products" | "designs" | "geography" | "content" | "seo";

export interface TableDef {
  /** The URL segment: `/catalogue/materials`. */
  key: string;
  zone: "catalogue" | "cms";
  section: Section;
  path: string;
  icon: IconName;
  read: string;
  manage: string;
  status: "CatalogStatus" | "ContentStatus" | null;
  columns: readonly string[];
  fields: readonly string[];
  required: readonly string[];
  /** Sent on create only — not in the update DTO. */
  createOnly: readonly string[];
  filters: readonly string[];
  /** Per-table overrides of `FIELD_KINDS`. */
  kinds: Record<string, FieldKind>;
  /** Excel import / export kind, when the catalogue offers one. */
  importKind?: Schemas["CatalogImportKind"];
  /** The contract has a `DELETE` for it; everything else archives through `status`. */
  deletable?: boolean;
  defaultSort?: string;
}

/** One table, its field names checked against the row, create and update DTOs. */
function define<Row extends keyof Schemas, Create extends keyof Schemas, Update extends keyof Schemas = Create>(def: {
  key: string;
  zone?: "catalogue" | "cms";
  section: Section;
  path: string;
  icon: IconName;
  read?: string;
  manage?: string;
  status?: "CatalogStatus" | "ContentStatus" | null;
  columns: readonly (keyof Schemas[Row] & string)[];
  fields: readonly (keyof Schemas[Create] & string)[];
  required: readonly (keyof Schemas[Create] & string)[];
  filters?: readonly string[];
  kinds?: Record<string, FieldKind>;
  importKind?: Schemas["CatalogImportKind"];
  deletable?: boolean;
  defaultSort?: string;
  /** Checked against the update DTO: whatever is not in it is sent on create only. */
  updatable?: readonly (keyof Schemas[Update] & string)[];
}): TableDef {
  const zone = def.zone ?? "catalogue";
  const updatable = def.updatable ? new Set<string>(def.updatable) : null;
  return {
    key: def.key,
    zone,
    section: def.section,
    path: def.path,
    icon: def.icon,
    read: def.read ?? (zone === "cms" ? "cms.manage" : "catalog.read"),
    manage: def.manage ?? (zone === "cms" ? "cms.manage" : "catalog.manage"),
    status: def.status === undefined ? (zone === "cms" ? "ContentStatus" : "CatalogStatus") : def.status,
    columns: def.columns,
    fields: def.fields,
    required: def.required,
    createOnly: updatable ? def.fields.filter((field) => !updatable.has(field)) : [],
    filters: def.filters ?? [],
    kinds: def.kinds ?? {},
    importKind: def.importKind,
    deletable: def.deletable,
    defaultSort: def.defaultSort,
  };
}

