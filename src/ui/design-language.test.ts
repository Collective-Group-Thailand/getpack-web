// @vitest-environment node
import { ESLint } from "eslint";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * Design language v3 (Phase 4 §4.0, §4.5, §4.6), held in CI rather than in reviewers' memory: the
 * source is read line by line and every pattern the language removed fails the build where it
 * reappears. Each rule names its file:line, so the failure says what to fix.
 *
 * Scope: everything the customer, admin and partner bundles are built from (`src/`), plus the
 * hand-written mocks and the e2e suite for the words. `src/lib/api/schema.d.ts` and
 * `mocks/generated/` are the API's contract, regenerated by `pnpm gen:api` — what they say is the
 * API's to change (docs/contract-requests.md), so they are not read here.
 */
const root = fileURLToPath(new URL("../../", import.meta.url));

function files(dir: string, extensions: RegExp): string[] {
  return readdirSync(join(root, dir)).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(join(root, path)).isDirectory()) return name === "generated" ? [] : files(path, extensions);
    return extensions.test(name) ? [path] : [];
  });
}

interface Hit {
  file: string;
  line: number;
  text: string;
}

function scan(paths: string[], pattern: RegExp, allow: (hit: Hit) => boolean = () => false): string[] {
  return paths.flatMap((file) =>
    readFileSync(join(root, file), "utf8")
      .split("\n")
      .flatMap((text, index) => {
        const hit = { file, line: index + 1, text };
        return pattern.test(text) && !allow(hit) ? [`${file}:${hit.line}  ${text.trim().slice(0, 140)}`] : [];
      }),
  );
}

// This file names every forbidden pattern, so it is never scanned itself.
const SELF = relative(root, fileURLToPath(import.meta.url));
const code = files("src", /\.(tsx?|css)$/).filter((file) => file !== SELF && !file.endsWith("schema.d.ts"));
// Share cards (`opengraph-image`, `seo/og-image`) are PNGs drawn by satori from inline styles: no CSS variables
// reach them, and they are images rather than the interface, so the interface's rules do not scan them.
const ui = code.filter(
  (file) => !/\.(test|stories)\.tsx?$/.test(file) && !/(opengraph-image|seo\/og-image)\.tsx$/.test(file),
);
const words = [...code, ...files("mocks", /\.ts$/), ...files("e2e", /\.ts$/)];

describe("design language v3", () => {
  it("has one typeface: no Trirong", () => {
    expect(scan(code, /trirong/i)).toEqual([]);
  });

  it("has no pill buttons", () => {
    expect(scan(code, /shape=["{]?["']?pill/)).toEqual([]);
  });

  it("has no eyebrow or kicker label", () => {
    expect(scan(ui, /\b(eyebrow|kicker)\b/i)).toEqual([]);
  });

  it("has no gradient — no gradient utility, no CSS gradient", () => {
    expect(scan(ui, /\bbg-(gradient|linear|radial|conic)-|(linear|radial|conic)-gradient\(/)).toEqual([]);
  });

  it("has no grain or noise overlay", () => {
    expect(scan(ui, /\bgrain\b|feTurbulence|fractalNoise/)).toEqual([]);
  });

  it("takes every radius from the tokens: no rounded-[…], no literal border-radius", () => {
    expect(scan(ui, /\brounded(-[a-z]+)?-\[/)).toEqual([]);
    // A radius in CSS or a style object is a token reference or nothing.
    expect(scan(ui, /border-?radius\s*:/i, (hit) => /var\(--radius-[a-z0-9]+\)/.test(hit.text))).toEqual([]);
  });

  it("draws circles, not pills: rounded-full only on a square", () => {
    // Square by its own size, or one of the few circles sized elsewhere (avatars and their buttons,
    // the 3D preview's floor shadow, the cart count's badge).
    const square = (text: string) => {
      if (/\bsize-(\d|\[|full)|aspect-square/.test(text)) return true;
      const h = /\bh-([\w.[\]]+)/.exec(text)?.[1];
      const w = /\b(?:min-)?w-([\w.[\]]+)/.exec(text)?.[1];
      return h !== undefined && h === w;
    };
    const circles = [
      "src/ui/components/Avatar.tsx",
      "src/features/admin/shell/AdminTopbar.tsx",
      "src/features/partner/shell/PartnerTopbar.tsx",
      "src/features/designer/components/BoxPreview3D.tsx",
      "src/ui/tokens/scale.ts",
    ];
    expect(scan(ui, /\brounded-full\b/, (hit) => square(hit.text) || circles.includes(hit.file))).toEqual([]);
  });

  it("puts no shadow on a button", () => {
    expect(scan(ui, /(<Button|buttonVariants\(|<IconButton)[^>]*\bshadow-(?!none)/)).toEqual([]);
    const button = readFileSync(join(root, "src/ui/components/Button.tsx"), "utf8");
    expect(button).not.toMatch(/\bshadow-(card|overlay|lift|cta)\b/);
  });
});

/*
 * Acceptance, re-scoped in the Phase 4 review: zero in UI copy, i18n and the enum→label mapping —
 * what a user can read. API-written text (problem details, notifications, settings labels) is
 * mapped at display by `src/i18n/terms.ts` until packio-api adopts the glossary; docs may quote
 * the old word (the docs/ui header note does).
 */
describe("Proof terminology (Phase 4 §4.5)", () => {
  // Built from parts so this file is not itself a hit for the repo-wide grep.
  const transliteration = ["ปรู", "๊ฟ"].join("");
  const never = new RegExp([transliteration, "ตัวอย่างงานพิมพ์", "พิสูจน์อักษร"].join("|"));

  it("never uses the transliteration or the other rejected words", () => {
    // The mapping layer and its test are the one place that must name the old words.
    const mapping = ["src/i18n/terms.ts", "src/i18n/terms.test.ts"];
    expect(
      scan(
        words.filter((file) => file !== SELF && !mapping.includes(file)),
        never,
      ),
    ).toEqual([]);
  });

  it("holds in every message file", () => {
    const messages = files("src/i18n/messages", /\.json$/);
    expect(messages.length).toBeGreaterThan(10);
    expect(scan(messages, never)).toEqual([]);
  });
});

describe("photos come from the CMS (Phase 4 §4.6)", { timeout: 60_000 }, () => {
  it("lints a stock-photo address as an error", async () => {
    const eslint = new ESLint({ cwd: root });
    const [result] = await eslint.lintText(
      // The hosts are assembled at run time so this file does not trip the rule it tests.
      [
        `export const a = "https://images.${"unsplash"}.com/photo-1";`,
        `export const b = "https://www.${"pexels"}.com/p/1";`,
      ].join("\n"),
      { filePath: join(root, "src/features/customer/home/x.ts"), warnIgnored: false },
    );
    const stock = (result?.messages ?? []).filter((message) => message.ruleId === "packio-photos/no-stock-photos");
    expect(stock).toHaveLength(2);
  });

  it("has no stock-photo address anywhere in the source", () => {
    expect(
      scan(
        [...code, ...files("mocks", /\.ts$/)].filter((file) => file !== SELF),
        /unsplash\.com|pexels\.com/i,
      ),
    ).toEqual([]);
  });
});
